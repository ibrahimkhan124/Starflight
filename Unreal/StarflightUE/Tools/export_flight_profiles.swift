import Foundation

@main struct ExportFlightProfiles {
    static func main() {
        let literal: (String) -> String = { value in
            "TEXT(\"" + value.replacingOccurrences(of: "\\", with: "\\\\")
                .replacingOccurrences(of: "\"", with: "\\\"") + "\")"
        }
        func number(_ value: Float) -> String { String(value) + "f" }
        let include = Set(CommandLine.arguments.dropFirst())
        print("// Generated by Tools/export_flight_profiles.sh from AlpineFlight's AircraftType.swift.")
        for ship in AircraftType.allCases where include.contains(ship.rawValue) {
            let tuning = [ship.cruiseSpeed, ship.response, ship.maximumPitch, ship.maximumRoll, ship.yawAuthority]
            let numbers = [ship.bodyRadius,ship.cityCollisionRadius,ship.length,ship.wingspan]
            print("    {\(literal(ship.rawValue)), \(literal(ship.name)), {\(tuning.map(number).joined(separator: ", "))}, \(numbers.map(number).joined(separator: ", "))},")
        }
    }
}
